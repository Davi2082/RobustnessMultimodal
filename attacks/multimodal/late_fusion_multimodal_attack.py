def main() -> None:
    args, text_parameters, image_parameters = parse_args()

    validate_args(
        args,
        text_parameters,
        image_parameters,
    )

    device = torch.device(DEVICE)
    device_mlm = torch.device(DEVICE_MLM)

    text_model_args = model_args_from_parameters(
        text_parameters,
        "text",
        args.text_model_path,
    )

    image_model_args = model_args_from_parameters(
        image_parameters,
        "image",
        args.image_model_path,
    )

    text_model, tokenizer, _ = load_model(
        device,
        text_model_args,
        str(args.text_model_path),
    )

    image_model, _, processor = load_model(
        device,
        image_model_args,
        str(args.image_model_path),
    )

    svm_fusion = None

    if args.fusion == "svm-rbf":
        fitted_svm = joblib.load(
            args.svm_model
        )

        svm_fusion = DifferentiableRBFSVMFusion(
            fitted_svm
        ).to(device)

    model = LateFusionClassifier(
        text_model=text_model,
        image_model=image_model,
        fusion=args.fusion,
        svm_fusion=svm_fusion,
        svm_input=args.svm_input,
    ).to(device)

    model.eval()

    # Existing BERTAttack helpers pass the fixed image only for multimodal
    # modalities. The actual two underlying models were already loaded above.
    args.modality = "feature-fusion"

    rephraser = None
    bertattack_tokenizer = None
    bertattack_mlm = None

    if args.attack_scope in {
        "text",
        "both",
    }:
        if args.attack_method == "trepat":
            rephraser = Rephraser(
                model=ATTACK_MODEL,
                device=device_mlm,
                command=COMMAND,
            )
        else:
            bertattack_tokenizer = (
                AutoTokenizer.from_pretrained(
                    "bert-base-uncased",
                    use_fast=True,
                )
            )

            bertattack_mlm = (
                AutoModelForMaskedLM.from_pretrained(
                    "bert-base-uncased"
                ).to(device_mlm)
            )

            bertattack_mlm.eval()

    dataset_classes, load_functions = (
        load_available_datasets()
    )

    if args.dataset not in dataset_classes:
        raise ValueError(
            f"Unknown dataset {args.dataset!r}; "
            f"available: {sorted(dataset_classes)}"
        )

    if args.test_data is None:
        candidates = sorted(
            glob.glob(
                f"data_loading/{args.dataset}/test.*"
            )
        )

        if not candidates:
            raise FileNotFoundError(
                f"No data_loading/{args.dataset}/test.* "
                "file was found"
            )

        test_data = Path(
            candidates[0]
        )

    else:
        test_data = args.test_data

    if not test_data.is_file():
        raise FileNotFoundError(
            f"Test annotations do not exist: "
            f"{test_data}"
        )

    images_dir = (
        args.images_dir
        if args.images_dir is not None
        else Path(
            f"data_loading/{args.dataset}/images"
        )
    )

    if not images_dir.is_dir():
        raise FileNotFoundError(
            f"Image directory does not exist: "
            f"{images_dir}"
        )

    dataset_test = my_datasets.get_dataset(
        dataset_classes[args.dataset],
        load_functions[args.dataset],
        args.n_tokens,
        processor,
        tokenizer,
        str(test_data),
        str(images_dir),
    )

    sampler = None

    if args.subset_size is not None:
        sampler = list(
            range(
                min(
                    args.subset_size,
                    len(dataset_test),
                )
            )
        )

    dataloader_test = DataLoader(
        dataset_test,
        batch_size=args.batch_size,
        shuffle=False,
        sampler=sampler,
        num_workers=args.num_workers,
    )

    output_dir = (
        args.output_dir
        if args.output_dir is not None
        else (
            args.results_path
            / "perturbed"
            / "late-fusion"
            / args.fusion
        )
    )

    dump_dir = (
        args.dump_dir
        if args.dump_dir is not None
        else (
            Path(LATE_FUSION_DATA_DIR)
            / args.fusion
            / args.attack_scope
        )
    )

    # Each launcher invocation owns exactly one output scenario, so separate
    # runs cannot overwrite another scenario's artifact.
    requested_scenarios = {
        args.attack_scope
    }

    active_budgets = []

    if args.attack_scope in {
        "text",
        "both",
    }:
        active_budgets.append(
            f"TRePAT max variants={args.max_variants}"
        )

    if args.attack_scope in {
        "image",
        "both",
    }:
        active_budgets.append(
            f"PGD iterations={args.pgd_iters}"
        )

    print(
        "Effective attack budget: "
        f"{', '.join(active_budgets)}"
    )

    output_names = ("scores", "logits", *COMPONENT_OUTPUT_NAMES)
    outputs = {
        scenario: {
            name: []
            for name in output_names
        }
        for scenario in requested_scenarios
    }

    labels_list: list[
        torch.Tensor
    ] = []

    indices_list: list[
        torch.Tensor
    ] = []

    similarities: list[
        float
    ] = []

    ssims: list[
        float
    ] = []

    perturbed_text_rows: list[
        dict[str, Any]
    ] = []

    attacked_samples = 0

    for (
        images,
        labels,
        texts,
        _,
        indices,
    ) in tqdm(
        dataloader_test,
        desc=(
            f"Fusion-aware "
            f"{args.fusion} attack"
        ),
        total=len(dataloader_test),
    ):
        images_device = move_to_device(
            images,
            device,
        )

        texts_device = move_to_device(
            texts,
            device,
        )

        with torch.inference_mode():
            clean_scores, _ = model(
                images_device,
                texts_device,
            )

        clean_predictions = (
            clean_scores
            .detach()
            .cpu()
            .reshape(-1)
            > args.threshold
        ).to(torch.int64)

        perturbed_texts: list[
            str
        ] = []

        perturbed_images: list[
            Image.Image
        ] = []

        for position, label in tqdm(
            enumerate(labels.tolist()),
            desc="Attacking batch samples",
            total=len(labels),
            leave=False,
        ):
            index = int(
                indices[position].item()
            )

            clean_news = {
                "txt": dataset_test.texts[
                    index
                ],
                "img": Image.open(
                    os.path.join(
                        dataset_test.img_dir,
                        dataset_test.imgs_path[index],
                    )
                ).convert("RGB"),
            }

            perturbed_text = clean_news[
                "txt"
            ]
            perturbed_image = clean_news[
                "img"
            ]
            text_similarity = 1.0
            image_ssim = 1.0

            clean_is_source = (
                int(
                    clean_predictions[
                        position
                    ].item()
                )
                == args.source_label
            )

            should_attack = (
                label == args.source_label
                and clean_is_source
            )

            if should_attack:
                attacked_samples += 1

                # Both calls deliberately receive clean_news. Therefore neither
                # modality attack observes the perturbation produced for the
                # other.
                if args.attack_scope in {
                    "text",
                    "both",
                }:
                    if args.attack_method == "trepat":
                        (
                            text_news,
                            text_similarity,
                        ) = fusion_trepat_attack(
                            model,
                            tokenizer,
                            processor,
                            args,
                            clean_news,
                            device,
                            rephraser,
                        )

                    else:
                        with torch.no_grad():
                            (
                                text_news,
                                text_similarity,
                            ) = bertattack_attack(
                                model,
                                tokenizer,
                                processor,
                                args,
                                clean_news,
                                label,
                                device,
                                bertattack_tokenizer,
                                bertattack_mlm,
                                device_mlm,
                            )

                    if (
                        text_similarity
                        >= args.min_txt_similarity
                    ):
                        perturbed_text = text_news[
                            "txt"
                        ]
                    else:
                        text_similarity = 1.0

                    perturbed_text_rows.append(
                        {
                            "index": index,
                            "original": clean_news["txt"],
                            "perturbed": perturbed_text,
                        }
                    )

                if args.attack_scope in {
                    "image",
                    "both",
                }:
                    (
                        image_news,
                        image_ssim,
                        _,
                    ) = img_perturbation(
                        model,
                        tokenizer,
                        processor,
                        args,
                        clean_news,
                        torch.tensor(
                            [label],
                            device=device,
                        ),
                    )

                    perturbed_image = image_news[
                        "img"
                    ]

                    image_ssim = float(
                        image_ssim.item()
                        if hasattr(
                            image_ssim,
                            "item",
                        )
                        else image_ssim
                    )

                    save_perturbed_image(
                        str(
                            dump_dir
                            / "images"
                        ),
                        index,
                        perturbed_image,
                    )

                if torch.cuda.is_available():
                    torch.cuda.empty_cache()

            perturbed_texts.append(
                perturbed_text
            )
            perturbed_images.append(
                perturbed_image
            )
            similarities.append(
                float(text_similarity)
            )
            ssims.append(
                float(image_ssim)
            )

        encoded_texts = None
        encoded_images = None

        if args.attack_scope in {
            "text",
            "both",
        }:
            encoded_texts = encode_text_batch(
                tokenizer,
                perturbed_texts,
                args.n_tokens,
                device,
            )

        if args.attack_scope in {
            "image",
            "both",
        }:
            encoded_images = encode_image_batch(
                processor,
                perturbed_images,
                device,
            )

        scenario_inputs = {
            "text": (images_device, encoded_texts),
            "image": (encoded_images, texts_device),
            "both": (encoded_images, encoded_texts),
        }

        with torch.inference_mode():
            for scenario in sorted(requested_scenarios):
                scenario_outputs = model(
                    *scenario_inputs[scenario],
                    return_components=True,
                )
                append_outputs(
                    outputs[scenario],
                    *scenario_outputs,
                )

        labels_list.append(
            torch.as_tensor(
                labels
            )
            .detach()
            .cpu()
            .reshape(-1)
        )

        indices_list.append(
            torch.as_tensor(
                indices
            )
            .detach()
            .cpu()
            .reshape(-1)
        )

    if not labels_list:
        raise ValueError(
            "The test dataloader produced no samples"
        )

    y_true = torch.cat(
        labels_list
    ).numpy()

    sample_indices = torch.cat(
        indices_list
    ).numpy()

    paths = scenario_paths(
        output_dir
    )

    for scenario in sorted(
        requested_scenarios
    ):
        scores = (
            torch.cat(
                outputs[scenario]["scores"]
            )
            .numpy()
            .reshape(-1)
        )

        logits = (
            torch.cat(
                outputs[scenario]["logits"]
            )
            .numpy()
            .reshape(-1)
        )

        component_outputs = {
            column: torch.cat(outputs[scenario][name]).numpy().reshape(-1)
            for column, name in zip(
                COMPONENT_OUTPUT_COLUMNS,
                COMPONENT_OUTPUT_NAMES,
            )
        }

        predictions = (
            scores > args.threshold
        ).astype(np.int64)

        result_path = paths[
            scenario
        ]

        result_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        save_predictions(
            y_true,
            predictions,
            scores,
            logits,
            sample_indices,
            str(result_path),
            ssims=(
                np.asarray(ssims)
                if scenario in {
                    "image",
                    "both",
                }
                else None
            ),
            txt_similarities=(
                np.asarray(similarities)
                if scenario in {
                    "text",
                    "both",
                }
                else None
            ),
            extra_columns=component_outputs,
        )

        save_parameters(
            result_path.parent
            / "parameters.json",
            scenario,
            args,
            text_parameters,
            image_parameters,
        )

        print(
            f"Saved {result_path}"
        )

    if perturbed_text_rows:
        save_perturbed_texts(
            str(dump_dir),
            perturbed_text_rows,
        )

    print(
        f"Attacked {attacked_samples} source-class samples "
        f"using the {args.fusion} fused score."
    )


