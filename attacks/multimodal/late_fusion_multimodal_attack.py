"""Run fusion-aware attacks against two late-fused unimodal classifiers.

The complete classifier attacked by this script is:

    fused_score = fusion(text_model(text), image_model(image))

The text and image perturbations are generated independently from the clean
sample. In particular:

* the text attack changes the text while keeping the clean image fixed;
* the image attack changes the image while keeping the clean text fixed;
* the both-perturbed result combines those two independently generated
  perturbations; it does not alternate or re-optimise them.

Despite this independence, both attacks optimise the fused score rather than
the output of one unimodal model. ``mean``, ``min`` and ``max`` use native
PyTorch operations. ``svm-rbf`` supports the ``StandardScaler + SVC``
pipeline generated by ``plot_multimodal_score_space.py`` and reproduces its
binary RBF decision function with differentiable PyTorch operations so that
PGD can backpropagate through the late-fusion classifier.

By default the output layout matches the existing late-fusion evaluation:

    results/.../perturbed/late-fusion/<fusion>/perturbed_results.csv
    results/.../perturbed/late-fusion/<fusion>/text-perturbed/...
    results/.../perturbed/late-fusion/<fusion>/image-perturbed/...

The first file is the independently both-perturbed scenario. Existing files
at those paths are replaced, consistently with the other attack scripts.
Every result CSV includes the fused output and the two component outputs used
by the score-space plot.

``--pgd-iters`` and ``--max-variants`` are the effective budgets used by one
invocation. A single-modality scope defaults to the full corresponding
unimodal budget; ``both`` defaults to half of each budget.
"""

